-- =========================================================
-- Perfil del usuario y ahorro personal
-- =========================================================
create or replace function public.update_my_profile(new_full_name text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'Sesión requerida';
  end if;
  if length(trim(coalesce(new_full_name, ''))) < 2 or length(trim(new_full_name)) > 80 then
    raise exception 'El nombre debe tener entre 2 y 80 caracteres';
  end if;
  update public.profiles
  set full_name = trim(new_full_name)
  where id = auth.uid();
  return found;
end;
$$;

revoke execute on function public.update_my_profile(text) from public, anon;
grant execute on function public.update_my_profile(text) to authenticated;

