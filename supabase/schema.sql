  calculator_name text not null,
  month date not null default date_trunc('month', now())::date,
  monthly_cost numeric(10,2) not null default 0 check (monthly_cost >= 0 and monthly_cost <= 100000),
  annual_cost numeric(10,2) not null default 0 check (annual_cost >= 0 and annual_cost <= 1200000),
  monthly_saving numeric(10,2) not null default 0 check (monthly_saving >= 0 and monthly_saving <= 100000),
  annual_saving numeric(10,2) not null default 0 check (annual_saving >= 0 and annual_saving <= 1200000),
  details jsonb not null default '{}'::jsonb,
