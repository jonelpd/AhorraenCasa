-- Ejecutar una vez en Supabase SQL Editor.

create table if not exists public.calculator_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  calculator_key text not null,
  calculator_name text not null,
  month date not null default date_trunc('month', now())::date,
  monthly_cost numeric(10,2) not null default 0 check (monthly_cost >= 0 and monthly_cost <= 100000),
  annual_cost numeric(10,2) not null default 0 check (annual_cost >= 0 and annual_cost <= 1200000),
  monthly_saving numeric(10,2) not null default 0 check (monthly_saving >= 0 and monthly_saving <= 100000),
  annual_saving numeric(10,2) not null default 0 check (annual_saving >= 0 and annual_saving <= 1200000),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.calculator_results enable row level security;

revoke all on table public.calculator_results from anon;
revoke all on table public.calculator_results from authenticated;

grant select, insert, delete on table public.calculator_results to authenticated;
grant usage, select on sequence public.calculator_results_id_seq to authenticated;

drop policy if exists "Users can view own calculator results" on public.calculator_results;
create policy "Users can view own calculator results"
on public.calculator_results
for select
to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert own calculator results" on public.calculator_results;
create policy "Users can insert own calculator results"
on public.calculator_results
for insert
to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete own calculator results" on public.calculator_results;
create policy "Users can delete own calculator results"
on public.calculator_results
for delete
to authenticated
using ((select auth.uid()) = user_id);

create index if not exists idx_calculator_results_user_created
on public.calculator_results(user_id, created_at desc);

create index if not exists idx_calculator_results_user_calculator
on public.calculator_results(user_id, calculator_key);
